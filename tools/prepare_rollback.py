"""Run from a checkout with release tags after setting FW_VERSION for a release."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[1]


def git(*args):
    return subprocess.check_output(["git", *args], cwd=root)


def number(version):
    return tuple(map(int, version.split(".")))


def selected_versions():
    pattern = r"(\d+\.\d+\.\d+)"
    header = (root / "FlightDeck/firmware_version.h").read_text()
    current = re.search('#define FW_VERSION "' + pattern + '"', header)[1]
    baseline = "1.1.0"
    versions = [tag[1:] for tag in git("tag", "--list").decode().splitlines()
                if re.fullmatch("v" + pattern, tag) and number(baseline) <= number(tag[1:]) < number(current)]
    if baseline not in versions:
        raise ValueError("Fetch release tags, including v1.1.0.")
    selected = sorted(versions, key=number, reverse=True)[:5]
    if baseline not in selected:
        selected.append(baseline)
    return current, selected


def archive_image(version, name, data):
    archive = root / "install/archive" / version / name
    archive.parent.mkdir(parents=True, exist_ok=True)
    if archive.exists():
        if archive.read_bytes() != data:
            raise ValueError(f"Refusing to replace archived v{version}/{name}")
    else:
        archive.write_bytes(data)


def main(usb=False):
    current, selected = selected_versions()
    entries = []
    catalog = []
    for version in ([current] if usb else []) + selected:
        def read(name):
            if version == current:
                return (root / "install" / name).read_bytes()
            return git("show", f"v{version}:install/{name}")

        manifest = json.loads(read("manifest.json"))
        app = read("FlightDeck.ino.bin")
        digest = hashlib.sha256(app).hexdigest()
        if (manifest != dict(device="lilygo-t-deck-esp32s3", version=version,
                             size=len(app), sha256=digest) or app[0] != 0xe9 or len(app) > 0x300000):
            raise ValueError(f"Invalid tagged application or manifest for v{version}")
        if version != current:
            archive_image(version, "FlightDeck.ino.bin", app)
        if usb:
            full = read("FlightDeck-full.bin")
            checksums = {name: sha for sha, name in
                         (line.split() for line in read("SHA256SUMS.txt").decode().splitlines())}
            if full[0x10000:] != app:
                raise ValueError(f"Full image does not contain the v{version} application")
            entry = {"version": version}
            for mode, name, data in [("update", "FlightDeck.ino.bin", app), ("full", "FlightDeck-full.bin", full)]:
                sha = hashlib.sha256(data).hexdigest()
                if sha != checksums[name]:
                    raise ValueError(f"Digest mismatch for v{version}/{name}")
                entry[mode] = {"sha256": sha, "md5": hashlib.md5(data).hexdigest()}
            if version != current:
                archive_image(version, "FlightDeck-full.bin", full)
            catalog.append(entry)
            continue
        entries.append(f'  {{"{version}","{digest}",{len(app)}}},')
    if usb:
        (root / "install/usb-releases.json").write_text(json.dumps(catalog, indent=2) + "\n", encoding="ascii")
        return
    (root / "FlightDeck/rollback_catalog.h").write_text(
        "// Generated by tools/prepare_rollback.py from verified release tags.\n"
        "static constexpr FirmwareOffer rollbackOffers[]={\n" + "\n".join(entries) + "\n};\n",
        encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--usb", action="store_true", help="Generate the USB catalog after packaging install/.")
    main(usb=parser.parse_args().usb)
